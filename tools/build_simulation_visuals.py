def parse_pcm_snapshot(path: Path) -> list[list[float]]:
    rows = []
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.reader(stream)
        next(reader)
        for row in reader:
            if len(row) >= 7:
                rows.append([float(row[1]), float(row[2]), float(row[5]), float(row[6])])
    unique = {(round(row[0], 12), round(row[1], 12)): row for row in rows}
    return list(unique.values())


