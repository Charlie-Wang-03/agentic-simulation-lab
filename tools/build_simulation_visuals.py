def expected_outputs() -> dict[Path, str]:
    evidence = {domain: read_json(evidence_path(domain)) for domain in DOMAINS}
    outputs = {visual_path(domain): RENDERERS[domain](evidence[domain]) for domain in DOMAINS}
    outputs[ASSET_ROOT / "montage.svg"] = render_montage(evidence)
    return outputs


def write_or_check(outputs: dict[Path, str], *, check: bool) -> int:
    stale = []
    for path, content in outputs.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(rel(path))
        else:
            if path.is_file() and path.read_text(encoding="utf-8") == content:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("stale simulation visuals: " + ", ".join(stale))
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import-local", action="store_true", help="import qualified ignored solver outputs into sanitized JSON")
    parser.add_argument("--check", action="store_true", help="fail if rendered SVG/PNG assets are stale")
    args = parser.parse_args(argv)
    if args.import_local and args.check:
        parser.error("--import-local and --check are mutually exclusive")
    if args.import_local:
        for domain in DOMAINS:
            path = evidence_path(domain)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(dump_json(IMPORTERS[domain]()), encoding="utf-8", newline="\n")
            print(f"imported {rel(path)}")
    missing = [rel(evidence_path(domain)) for domain in DOMAINS if not evidence_path(domain).is_file()]
    if missing:
        print("missing sanitized evidence: " + ", ".join(missing))
        return 2
    evidence = {domain: read_json(evidence_path(domain)) for domain in DOMAINS}
    status = write_or_check(expected_outputs(), check=args.check)
    status |= render_or_check_pngs(evidence, check=args.check)
    if not status:
        print("simulation visuals: PASS" if args.check else "simulation visuals: built")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
