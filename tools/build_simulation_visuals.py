def _load_plotting() -> tuple[Any, Any, Any]:
    """Load the optional documentation-visual stack only when PNGs are handled."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.tri as mtri
        from PIL import Image
    except ImportError as exc:
        raise RuntimeError("paper-style PNG generation requires the 'visuals' extra") from exc
    plt.rcParams.update({"axes.titlesize": 10, "axes.labelsize": 9, "font.size": 9})
    return plt, mtri, Image


def _figure(plt: Any, evidence: dict[str, Any], title: str, *, width_ratios: list[float] | None = None) -> tuple[Any, Any]:
    columns = 1 if width_ratios is None else len(width_ratios)
    figure, axes = plt.subplots(
        1,
        columns,
        figsize=(PNG_SIZE[0] / PNG_DPI, PNG_SIZE[1] / PNG_DPI),
        constrained_layout=True,
        gridspec_kw={"width_ratios": width_ratios} if width_ratios else None,
        squeeze=False,
    )
    figure.get_layout_engine().set(rect=(0.05, 0.08, 0.98, 0.82))
    figure.suptitle(title, fontsize=15, fontweight="bold", y=0.98)
    figure.text(0.5, 0.915, evidence["solver"], ha="center", va="top", fontsize=8.5, color="#475569")
    figure.text(
        0.02,
        0.018,
        f"Solver-derived compact evidence · {evidence['domain']}/{evidence['case']} · status {evidence['status']}",
        ha="left",
        va="bottom",
        fontsize=7.5,
        color="#64748b",
        zorder=10,
    )
    return figure, axes[0]


def _style_axis(axis: Any, *, equal: bool = False) -> None:
    axis.tick_params(labelsize=8, direction="out")
    axis.grid(False)
    for spine in axis.spines.values():
        spine.set_linewidth(0.7)
        spine.set_color("#64748b")
    if equal:
        axis.set_aspect("equal", adjustable="box")


def _colorbar(figure: Any, artist: Any, axis: Any, label: str) -> None:
    bar = figure.colorbar(artist, ax=axis, pad=0.025, fraction=0.052)
    bar.set_label(label, fontsize=9)
    bar.ax.tick_params(labelsize=8)


def _tri_field(axis: Any, mtri: Any, coordinates: Any, values: Any, *, cmap: str, levels: int = 20) -> Any:
    points = np.asarray(coordinates, dtype=float)
    field = np.asarray(values, dtype=float)
    triangulation = mtri.Triangulation(points[:, 0], points[:, 1])
    return axis.tricontourf(triangulation, field, levels=levels, cmap=cmap, extend="both")


def _grid_field(axis: Any, coordinates: Any, values: Any, *, cmap: str, levels: int = 20) -> Any:
    points = np.asarray(coordinates, dtype=float)
    field = np.asarray(values, dtype=float)
    xs = np.unique(points[:, 0])
    ys = np.unique(points[:, 1])
    if len(xs) * len(ys) != len(points):
        _, mtri, _ = _load_plotting()
        return _tri_field(axis, mtri, points, field, cmap=cmap, levels=levels)
    lookup = {(x, y): value for (x, y), value in zip(points, field, strict=True)}
    grid = np.asarray([[lookup[(x, y)] for x in xs] for y in ys])
    return axis.contourf(xs, ys, grid, levels=levels, cmap=cmap, extend="both")


