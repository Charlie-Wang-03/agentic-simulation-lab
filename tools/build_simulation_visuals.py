def render_mechanics(e: dict[str, Any]) -> str:
    coords = e["data"]["coordinates"]
    disp = e["data"]["displacement"]
    stress = e["data"]["equivalent_stress"]
    projected = [[p[0] + 0.55 * p[1], p[2] - 0.35 * p[1]] for p in coords]
    body = circles(projected, disp, box=(78, 150, 700, 190), radius=3.4)
    body += '<line x1="78" y1="130" x2="78" y2="385" stroke="#d6e6ef" stroke-width="5"/><text x="78" y="420" text-anchor="middle" class="label">fixed</text>'
    body += f'<text x="80" y="125" class="label">621 SOLID186 nodes · max stress {max(stress)/1e6:.3f} MPa</text>'
    return frame("3-D cantilever displacement field", "Mechanical solution mapped back to the imported SOLID186 mesh", body, legend_spec=("|u| [m]", min(disp), max(disp)), footer="mechanics/static-cantilever · fresh Mechanical 2026 R1 result")


