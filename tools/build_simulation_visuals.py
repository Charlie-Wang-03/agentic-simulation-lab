def rel(path: Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sources(*paths: Path) -> list[dict[str, str]]:
    return [{"path": rel(path), "sha256": sha256(path)} for path in paths]


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def require_pass(path: Path) -> dict[str, Any]:
    payload = read_json(path)
    if payload.get("status") != "PASS":
        raise ValueError(f"source result is not PASS: {rel(path)}")
    return payload


def base_evidence(
    domain: str,
    *,
    solver: str,
    representation: str,
    reference: str,
    source_files: Iterable[Path],
    rerun: bool,
) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "domain": domain,
        "case": SLUGS[domain],
        "status": "PASS",
        "solver": solver,
        "representation": representation,
        "provenance": {
            "reference": reference,
            "source_files": sources(*source_files),
            "solver_rerun_required_for_this_import": rerun,
            "qualification": "Numeric samples imported from the exact qualified benchmark output; no values were fabricated.",
        },
    }


def parse_cdb_nodes(path: Path) -> dict[int, list[float]]:
    nodes: dict[int, list[float]] = {}
    in_block = False
    expected = 0
    for line in path.read_text(encoding="ascii", errors="replace").splitlines():
        if line.startswith("NBLOCK"):
            in_block = True
            expected = int(line.split(",")[-1])
            continue
        if not in_block or line.startswith("("):
            continue
        if line.strip().startswith("-1"):
            break
        if len(line) >= 27:
            node_id = int(line[:9])
            # NBLOCK's declared ``(3i9,6e21.13e3)`` fixed-width format may
            # omit a trailing zero coordinate as a blank field.
            fields = [line[start : start + 21].strip() for start in (27, 48, 69)]
            nodes[node_id] = [float(value) if value else 0.0 for value in fields]
            if len(nodes) == expected:
                break
    if not nodes:
        raise ValueError(f"no CDB nodes parsed from {rel(path)}")
    return nodes


def parse_result_table(path: Path) -> dict[int, float]:
    result: dict[int, float] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines()[1:]:
        parts = line.split()
        if len(parts) >= 2:
            try:
                result[int(parts[0])] = float(parts[1])
            except ValueError:
                continue
    if not result:
        raise ValueError(f"no result values parsed from {rel(path)}")
    return result


def import_mechanics() -> dict[str, Any]:
    out = ROOT / "artifacts/runs/mechanics/static-cantilever/20260821T153709Z/outputs"
    result = out / "static_cantilever_results.json"
    cdb = out / "static_cantilever_model.cdb"
    deformation_file = out / "static_cantilever_deformation.txt"
    stress_file = out / "static_cantilever_equivalent_stress.txt"
    payload = require_pass(result)
    nodes = parse_cdb_nodes(cdb)
    deformation = parse_result_table(deformation_file)
    stress = parse_result_table(stress_file)
    common = sorted(nodes.keys() & deformation.keys() & stress.keys())
    if len(common) != payload["mesh"]["node_count"]:
        raise ValueError("mechanics evidence does not cover every solved node")
    evidence = base_evidence(
        "mechanics",
        solver="Mechanical 2026 R1 / MAPDL 261",
        representation="3-D nodal displacement magnitude and equivalent stress",
        reference="artifacts/runs/mechanics/static-cantilever/20260821T153709Z/run.json",
        source_files=(result, cdb, deformation_file, stress_file),
        rerun=True,
    )
    evidence["units"] = {"coordinates": "m", "displacement": "m", "equivalent_stress": "Pa"}
    evidence["validation"] = {
        "maximum_displacement_m": payload["results"]["maximum_total_deformation_m"],
        "maximum_equivalent_stress_pa": payload["results"]["maximum_equivalent_stress_pa"],
        "deflection_relative_error": payload["results"]["relative_error"],
    }
    evidence["data"] = {
        "node_id": common,
        "coordinates": [nodes[node] for node in common],
        "displacement": [deformation[node] for node in common],
        "equivalent_stress": [stress[node] for node in common],
    }
    return evidence


