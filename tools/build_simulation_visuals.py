def color(value: float, minimum: float, maximum: float) -> str:
    fraction = 0.5 if maximum <= minimum else min(1.0, max(0.0, (value - minimum) / (maximum - minimum)))
    return PALETTE[min(len(PALETTE) - 1, int(fraction * len(PALETTE)))]


def fit(values: Iterable[float], start: float, span: float, *, reverse: bool = False) -> tuple[dict[float, float], float, float]:
    values = list(values)
    low, high = min(values), max(values)
    scale = span / max(high - low, 1e-30)
    mapped = {value: start + (high - value if reverse else value - low) * scale for value in set(values)}
    return mapped, low, high


def circles(points: list[list[float]], values: list[float], *, box: tuple[float, float, float, float], radius: float = 2.5) -> str:
    x0, y0, width, height = box
    xs, ys = [point[0] for point in points], [point[1] for point in points]
    xmap, _, _ = fit(xs, x0, width)
    ymap, _, _ = fit(ys, y0, height, reverse=True)
    vmin, vmax = min(values), max(values)
    return "".join(f'<circle cx="{xmap[x]:.2f}" cy="{ymap[y]:.2f}" r="{radius:.2f}" fill="{color(value, vmin, vmax)}"/>' for (x, y), value in zip(points, values, strict=True))


def line_plot(xs: list[float], ys: list[float], *, box: tuple[float, float, float, float], stroke: str, width: float = 4) -> str:
    x0, y0, w, h = box
    xmap, _, _ = fit(xs, x0, w)
    ymap, _, _ = fit(ys, y0, h, reverse=True)
    points = " ".join(f"{xmap[x]:.2f},{ymap[y]:.2f}" for x, y in zip(xs, ys, strict=True))
    return f'<polyline points="{points}" fill="none" stroke="{stroke}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>'


