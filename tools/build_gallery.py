def build(check: bool) -> list[str]:
    catalog = load_catalog()
    domains = list(catalog["domains"])
    cases = [case for domain in domains for case in domain["cases"]]
    counts = Counter(str(case["status"]) for case in cases)
    outputs = {
        ASSETS / "hero.svg": hero_svg(len(cases), len(domains), counts),
        ASSETS / "showcase-board.svg": showcase_board_svg(),
        ASSETS / "workflow.svg": workflow_svg(),
        ROOT / "docs" / "BENCHMARKS.md": gallery_markdown(catalog, chinese=False),
        ROOT / "docs" / "BENCHMARKS.zh-CN.md": gallery_markdown(catalog, chinese=True),
    }
    for relative, rendered in showcase_svgs().items():
        outputs[ASSETS / relative] = rendered
    for domain in domains:
        outputs[ASSETS / "gallery" / f"{domain['domain']}.svg"] = domain_svg(domain)
    errors: list[str] = []
    for path, content in outputs.items():
        write_output(path, content, check, errors)
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated gallery content is stale")
    args = parser.parse_args()
    errors = build(args.check)
    for error in errors:
        print(error)
    return bool(errors)


if __name__ == "__main__":
    raise SystemExit(main())
