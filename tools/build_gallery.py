def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def load_catalog() -> dict[str, object]:
    return json.loads(CATALOG.read_text(encoding="utf-8"))


def case_source(case: dict[str, object]) -> str:
    path = ROOT / str(case["entrypoint"])
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return str(case.get("analysis") or case["title"])
    doc = ast.get_docstring(tree) or str(case.get("analysis") or case["title"])
    first = doc.splitlines()[0].strip()
    if ":" in first and first.lower().startswith(("case ", "phase ")):
        first = first.split(":", 1)[1].strip()
    return first.rstrip(".")


def declared_checks(case: dict[str, object]) -> list[str]:
    path = ROOT / str(case["entrypoint"])
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Assign, ast.AnnAssign)):
            continue
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        if not any(isinstance(target, ast.Name) and target.id == "checks" for target in targets):
            continue
        value = node.value
        if isinstance(value, ast.Dict):
            keys = [key.value for key in value.keys if isinstance(key, ast.Constant) and isinstance(key.value, str)]
            return keys[:3]
    return []


def validation_text(domain: str, case: dict[str, object]) -> str:
    key = (domain, str(case["slug"]))
    if key in CURATED_VALIDATION:
        return CURATED_VALIDATION[key]
    checks = declared_checks(case)
    if checks:
        return "; ".join(item.replace("_", " ") for item in checks)
    if case.get("evidence"):
        return "Compact historical evidence is linked; no case-specific metric is duplicated here"
    return "No attributable run evidence; status remains NOT_RUN"


def svg_document(title: str, desc: str, body: str, *, height: int = 420, background: str = "#081018") -> str:
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="{height}" viewBox="0 0 1200 {height}" role="img" aria-labelledby="title desc">
{MARKER}
<title id="title">{esc(title)}</title>
<desc id="desc">{esc(desc)}</desc>
<rect width="1200" height="{height}" rx="28" fill="{background}"/>
{body}
</svg>
'''


def write_output(path: Path, content: str, check: bool, errors: list[str]) -> None:
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            errors.append(f"{path.relative_to(ROOT).as_posix()} is stale")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


