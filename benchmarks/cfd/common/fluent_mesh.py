"""Small deterministic Fluent ASCII mesh generators for CFD smoke tests."""

from __future__ import annotations

import math
from collections import defaultdict
from pathlib import Path
from typing import Callable, Iterable


Point = tuple[float, ...]


BC_TYPE = {
    "interior": 2,
    "wall": 3,
    "pressure-inlet": 4,
    "pressure-outlet": 5,
    "symmetry": 7,
    "periodic-shadow": 8,
    "pressure-far-field": 9,
    "velocity-inlet": 10,
    "periodic": 12,
    "axis": 14,
}


def _hx(value: int) -> str:
    return format(value, "x")


def write_fluent_ascii(
    path: Path,
    *,
    dimension: int,
    points: list[Point],
    cells: list[tuple[int, ...]],
    boundary_name: Callable[[tuple[int, ...], Point], tuple[str, str]],
    fluid_zone_name: str = "fluid",
    cell_zone_names: list[str] | None = None,
    cell_zone_types: dict[str, str] | None = None,
) -> dict[str, int]:
    """Write a conformal all-quad/all-hex Fluent legacy ASCII mesh."""
    if dimension not in (2, 3):
        raise ValueError("dimension must be 2 or 3")
    local_faces = (
        ((0, 1), (1, 2), (2, 3), (3, 0))
        if dimension == 2
        else (
            (0, 3, 2, 1),
            (4, 5, 6, 7),
            (0, 1, 5, 4),
            (1, 2, 6, 5),
            (2, 3, 7, 6),
            (3, 0, 4, 7),
        )
    )
    faces: dict[tuple[int, ...], list[object]] = {}
    for cell_id, cell in enumerate(cells, start=1):
        for face_def in local_faces:
            ordered = tuple(cell[i] for i in face_def)
            # Fluent's 3-D legacy format uses the opposite winding from the
            # conventional outward-oriented hexahedral face lists above.
            if dimension == 3:
                ordered = tuple(reversed(ordered))
            key = tuple(sorted(ordered))
            if key in faces:
                faces[key][2] = cell_id
            else:
                faces[key] = [ordered, cell_id, 0]

    if cell_zone_names is None:
        cell_zone_names=[fluid_zone_name]*len(cells)
    if len(cell_zone_names)!=len(cells):
        raise ValueError("cell_zone_names length must match cells")
    ordered_cell_zones=list(dict.fromkeys(cell_zone_names))
    zones: dict[tuple[str, str], list[tuple[tuple[int, ...], int, int]]] = defaultdict(list)
    interior_zones: dict[tuple[str, str], list[tuple[tuple[int, ...], int, int]]] = defaultdict(list)
    for ordered, c0, c1 in faces.values():
        item = (ordered, int(c0), int(c1))
        if c1:
            zone_one = cell_zone_names[int(c0)-1]
            zone_two = cell_zone_names[int(c1)-1]
            if zone_one == zone_two:
                name = "interior" if len(ordered_cell_zones) == 1 else f"interior-{zone_one}"
                zone_type = "interior"
            else:
                name = f"{zone_one}-{zone_two}-interface"
                # An internal face shared by unlike cell-zone types must be a
                # two-sided wall. Fluent creates/couples the shadow side.
                zone_type = "wall"
            interior_zones[(name, zone_type)].append(item)
        else:
            centroid = tuple(sum(points[n][d] for n in ordered) / len(ordered) for d in range(dimension))
            zones[boundary_name(ordered, centroid)].append(item)

    path.parent.mkdir(parents=True, exist_ok=True)
    node_count, cell_count = len(points), len(cells)
    total_faces = sum(len(items) for items in interior_zones.values()) + sum(len(items) for items in zones.values())
    lines = [
        '(0 "Generated by agentic-simulation-lab")',
        f"(2 {dimension})",
        f"(10 (0 1 {_hx(node_count)} 0 {dimension}))",
        f"(10 (1 1 {_hx(node_count)} 1 {dimension})(",
    ]
    lines.extend(" ".join(f"{v:.16g}" for v in p) for p in points)
    lines += ["))", f"(12 (0 1 {_hx(cell_count)} 0))"]
    cell_zone_meta=[]
    for offset,name in enumerate(ordered_cell_zones):
        ids=[i+1 for i,n in enumerate(cell_zone_names) if n==name]
        if ids!=list(range(min(ids),max(ids)+1)):
            raise ValueError("cells in each named zone must be contiguous")
        zid=2+offset; lines.append(f"(12 ({_hx(zid)} {_hx(min(ids))} {_hx(max(ids))} 1 {4 if dimension == 3 else 3}))");cell_zone_meta.append((zid,name))
    lines.append(f"(13 (0 1 {_hx(total_faces)} 0))")

    next_face = 1
    zone_meta: list[tuple[int, str, str]] = []
    all_zones = [(name, zone_type, items) for (name, zone_type), items in sorted(interior_zones.items())] + [
        (name, zone_type, items) for (name, zone_type), items in sorted(zones.items())
    ]
    zone_id = 2+len(ordered_cell_zones)
    for name, zone_type, items in all_zones:
        if not items:
            continue
        start, end = next_face, next_face + len(items) - 1
        face_type = 4 if dimension == 3 else 2
        lines.append(f"(13 ({_hx(zone_id)} {_hx(start)} {_hx(end)} {_hx(BC_TYPE[zone_type])} {face_type})(")
        for nodes, c0, c1 in items:
            lines.append(" ".join([*(_hx(n + 1) for n in nodes), _hx(c0), _hx(c1)]))
        lines.append("))")
        zone_meta.append((zone_id, name, zone_type))
        next_face = end + 1
        zone_id += 1
    cell_zone_types = cell_zone_types or {}
    for zid,name in cell_zone_meta:
        zone_type = cell_zone_types.get(name, "fluid")
        if zone_type not in {"fluid", "solid"}:
            raise ValueError(f"unsupported cell zone type {zone_type!r} for {name!r}")
        # Section 45 zone identifiers are decimal even though section 12/13
        # index ranges use hexadecimal notation.
        lines.append(f'(45 ({zid} {zone_type} {name})())')
    for zid, name, zone_type in zone_meta:
        lines.append(f'(45 ({zid} {zone_type} {name})())')
    path.write_text("\n".join(lines) + "\n", encoding="ascii")
    return {
        "nodes": node_count,
        "cells": cell_count,
        "faces": total_faces,
        "boundary_zones": len(zones),
        "fluid_zones": len(ordered_cell_zones),
    }


def rectangular_2d(
    path: Path,
    xs: list[float],
    ys: list[float],
    *,
    left: tuple[str, str] = ("inlet", "velocity-inlet"),
    right: tuple[str, str] = ("outlet", "pressure-outlet"),
    bottom: tuple[str, str] = ("bottom-wall", "wall"),
    top: tuple[str, str] = ("top-wall", "wall"),
) -> dict[str, int]:
    nx, ny = len(xs), len(ys)
    points = [(x, y) for y in ys for x in xs]
    nid = lambda i, j: j * nx + i
    cells = [
        (nid(i, j), nid(i + 1, j), nid(i + 1, j + 1), nid(i, j + 1))
        for j in range(ny - 1)
        for i in range(nx - 1)
    ]
    tol = 1e-10 * max(abs(xs[-1] - xs[0]), abs(ys[-1] - ys[0]), 1.0)

    def boundary(_nodes: tuple[int, ...], c: Point) -> tuple[str, str]:
        if abs(c[0] - xs[0]) < tol:
            return left
        if abs(c[0] - xs[-1]) < tol:
            return right
        if abs(c[1] - ys[0]) < tol:
            return bottom
        if abs(c[1] - ys[-1]) < tol:
            return top
        raise ValueError(f"unclassified boundary at {c}")

    return write_fluent_ascii(path, dimension=2, points=points, cells=cells, boundary_name=boundary)


def pipe_3d(path: Path, *, diameter: float, length: float, nxy: int, nx: int) -> dict[str, int]:
    radius = diameter / 2.0
    axial = [length * i / nx for i in range(nx + 1)]
    uv = [-1.0 + 2.0 * i / nxy for i in range(nxy + 1)]
    def concentric(u: float, v: float) -> tuple[float, float]:
        # Shirley-Chiu concentric square-to-disk map: non-degenerate at corners.
        if abs(u) < 1e-15 and abs(v) < 1e-15:
            return (0.0, 0.0)
        if abs(u) > abs(v):
            rr, theta = u, (math.pi / 4.0) * (v / u)
        else:
            rr, theta = v, (math.pi / 2.0) - (math.pi / 4.0) * (u / v)
        return (radius * rr * math.cos(theta), radius * rr * math.sin(theta))
    cross = [concentric(u, v) for v in uv for u in uv]
    nc = len(cross)
    points = [(x, y, z) for x in axial for y, z in cross]
    nid = lambda i, j, k: i * nc + k * (nxy + 1) + j
    cells = [
        (
            nid(i, j, k), nid(i + 1, j, k), nid(i + 1, j + 1, k), nid(i, j + 1, k),
            nid(i, j, k + 1), nid(i + 1, j, k + 1), nid(i + 1, j + 1, k + 1), nid(i, j + 1, k + 1),
        )
        for i in range(nx)
        for k in range(nxy)
        for j in range(nxy)
    ]
    tol = 1e-10

    def boundary(_nodes: tuple[int, ...], c: Point) -> tuple[str, str]:
        if abs(c[0]) < tol:
            return ("inlet", "velocity-inlet")
        if abs(c[0] - length) < tol:
            return ("outlet", "pressure-outlet")
        return ("pipe-wall", "wall")

    return write_fluent_ascii(path, dimension=3, points=points, cells=cells, boundary_name=boundary)


def cylinder_ogrid_2d(
    path: Path, *, radius: float, half_length: float, half_height: float, nr: int, nt: int
) -> dict[str, int]:
    points: list[Point] = []
    for i in range(nr + 1):
        s = i / nr
        # Gentle clustering at the cylinder while reaching a rectangular far field.
        blend = s ** 1.35
        for j in range(nt):
            theta = 2.0 * math.pi * j / nt
            ct, st = math.cos(theta), math.sin(theta)
            r_outer = min(
                half_length / max(abs(ct), 1e-14),
                half_height / max(abs(st), 1e-14),
            )
            r = radius + blend * (r_outer - radius)
            points.append((r * ct, r * st))
    nid = lambda i, j: i * nt + (j % nt)
    cells = [
        (nid(i, j), nid(i + 1, j), nid(i + 1, j + 1), nid(i, j + 1))
        for i in range(nr)
        for j in range(nt)
    ]
    inner_limit = radius * 1.001

    def boundary(_nodes: tuple[int, ...], c: Point) -> tuple[str, str]:
        if math.hypot(c[0], c[1]) < inner_limit:
            return ("cylinder", "wall")
        dx = abs(abs(c[0]) - half_length)
        dy = abs(abs(c[1]) - half_height)
        if dx <= dy and c[0] < 0:
            return ("inlet", "velocity-inlet")
        if dx <= dy:
            return ("outlet", "pressure-outlet")
        return ("far-symmetry", "symmetry")

    return write_fluent_ascii(path, dimension=2, points=points, cells=cells, boundary_name=boundary)


def block_wind_tunnel_3d(
    path: Path,
    *,
    xs: list[float], ys: list[float], zs: list[float],
    block: tuple[float, float, float, float, float, float],
) -> dict[str, int]:
    nx, ny, nz = len(xs), len(ys), len(zs)
    points = [(x, y, z) for z in zs for y in ys for x in xs]
    nid = lambda i, j, k: k * ny * nx + j * nx + i
    x0, x1, y0, y1, z0, z1 = block
    cells = []
    for k in range(nz - 1):
        for j in range(ny - 1):
            for i in range(nx - 1):
                cx, cy, cz = (xs[i] + xs[i+1])/2, (ys[j]+ys[j+1])/2, (zs[k]+zs[k+1])/2
                if x0 < cx < x1 and y0 < cy < y1 and z0 < cz < z1:
                    continue
                cells.append((
                    nid(i,j,k), nid(i+1,j,k), nid(i+1,j+1,k), nid(i,j+1,k),
                    nid(i,j,k+1), nid(i+1,j,k+1), nid(i+1,j+1,k+1), nid(i,j+1,k+1),
                ))
    tol = 1e-9

    def boundary(_nodes: tuple[int, ...], c: Point) -> tuple[str, str]:
        if abs(c[0] - xs[0]) < tol:
            return ("inlet", "velocity-inlet")
        if abs(c[0] - xs[-1]) < tol:
            return ("outlet", "pressure-outlet")
        on_block = (
            x0-tol <= c[0] <= x1+tol and y0-tol <= c[1] <= y1+tol and z0-tol <= c[2] <= z1+tol
            and (abs(c[0]-x0)<tol or abs(c[0]-x1)<tol or abs(c[1]-y0)<tol or abs(c[1]-y1)<tol or abs(c[2]-z0)<tol or abs(c[2]-z1)<tol)
        )
        if on_block:
            return ("model-wall", "wall")
        if abs(c[2] - zs[0]) < tol:
            return ("floor", "wall")
        return ("tunnel-symmetry", "symmetry")

    return write_fluent_ascii(path, dimension=3, points=points, cells=cells, boundary_name=boundary)


def nozzle_2d(
    path: Path,
    *,
    length: float,
    throat_x: float,
    inlet_half_height: float,
    throat_half_height: float,
    exit_half_height: float,
    nx: int,
    ny: int,
) -> dict[str, int]:
    xs = [length * i / nx for i in range(nx + 1)]
    points: list[Point] = []
    for j in range(ny + 1):
        eta = -1.0 + 2.0*j/ny
        for x in xs:
            if x <= throat_x:
                q = x/throat_x
                half = inlet_half_height + (throat_half_height-inlet_half_height)*(0.5-0.5*math.cos(math.pi*q))
            else:
                q = (x-throat_x)/(length-throat_x)
                half = throat_half_height + (exit_half_height-throat_half_height)*(0.5-0.5*math.cos(math.pi*q))
            points.append((x, eta*half))
    nid = lambda i,j: j*(nx+1)+i
    cells = [(nid(i,j),nid(i+1,j),nid(i+1,j+1),nid(i,j+1)) for j in range(ny) for i in range(nx)]
    tol=1e-10
    def boundary(_nodes: tuple[int,...], c: Point) -> tuple[str,str]:
        if abs(c[0])<tol:
            return ("inlet","pressure-inlet")
        if abs(c[0]-length)<tol:
            return ("outlet","pressure-outlet")
        return ("nozzle-wall","wall")
    return write_fluent_ascii(path, dimension=2, points=points, cells=cells, boundary_name=boundary)


def backward_step_2d(path: Path, *, h: float, nx_up: int, nx_down: int, ny_up: int, ny_step: int) -> dict[str, int]:
    """Structured, conformal 2-D backward-facing-step mesh (expansion ratio 1.5)."""
    xs = [-4*h + 4*h*i/nx_up for i in range(nx_up)] + [30*h*i/nx_down for i in range(nx_down+1)]
    ys = [h*j/ny_step for j in range(ny_step)] + [h + 2*h*j/ny_up for j in range(ny_up+1)]
    nx, ny = len(xs), len(ys)
    points = [(x,y) for y in ys for x in xs]
    nid = lambda i,j: j*nx+i
    cells=[]
    for j in range(ny-1):
        for i in range(nx-1):
            cx=(xs[i]+xs[i+1])/2; cy=(ys[j]+ys[j+1])/2
            if cx < 0 and cy < h:
                continue
            cells.append((nid(i,j),nid(i+1,j),nid(i+1,j+1),nid(i,j+1)))
    tol=1e-9*h
    def boundary(_nodes: tuple[int,...], c: Point) -> tuple[str,str]:
        if abs(c[0]+4*h)<tol: return ("inlet","velocity-inlet")
        if abs(c[0]-30*h)<tol: return ("outlet","pressure-outlet")
        if abs(c[0])<tol and c[1] < h+tol: return ("step-wall","wall")
        if c[0] < 0 and abs(c[1]-h)<tol: return ("lower-wall","wall")
        if c[0] >= 0 and abs(c[1])<tol: return ("lower-wall","wall")
        return ("upper-wall","wall")
    result=write_fluent_ascii(path,dimension=2,points=points,cells=cells,boundary_name=boundary)
    result.update({"nx_upstream":nx_up,"nx_downstream":nx_down,"ny_upstream":ny_up,"ny_step":ny_step})
    return result


def naca0012_ogrid_2d(path: Path, *, angle_deg: float, nr: int, nt: int, far: float = 15.0) -> dict[str, int]:
    """Mapped O-grid around a NACA 0012, rotated about quarter chord."""
    if nt % 2:
        raise ValueError("nt must be even")
    # Positive aerodynamic AoA: chord rotated clockwise relative to +x flow.
    alpha=-math.radians(angle_deg)
    surface=[]
    for j in range(nt):
        if j < nt//2:
            q=j/(nt//2); x=0.5*(1+math.cos(math.pi*q)); sign=1.0
        else:
            q=(j-nt//2)/(nt//2); x=0.5*(1-math.cos(math.pi*q)); sign=-1.0
        yt=5*0.12*(0.2969*math.sqrt(max(x,0))-0.1260*x-0.3516*x*x+0.2843*x**3-0.1036*x**4)
        xr=x-0.25; yr=sign*yt
        surface.append((0.25+xr*math.cos(alpha)-yr*math.sin(alpha),xr*math.sin(alpha)+yr*math.cos(alpha)))
    points=[]
    for i in range(nr+1):
        blend=(i/nr)**1.35
        for j,(xi,yi) in enumerate(surface):
            theta=2*math.pi*j/nt; ct,st=math.cos(theta),math.sin(theta)
            rr=min(far/max(abs(ct),1e-14),far/max(abs(st),1e-14))
            xo=0.25+rr*ct; yo=rr*st
            points.append((xi+blend*(xo-xi),yi+blend*(yo-yi)))
    nid=lambda i,j:i*nt+(j%nt)
    cells=[(nid(i,j),nid(i+1,j),nid(i+1,j+1),nid(i,j+1)) for i in range(nr) for j in range(nt)]
    def boundary(_nodes: tuple[int,...], c: Point) -> tuple[str,str]:
        if math.hypot(c[0]-0.25,c[1]) < 2.0: return ("airfoil","wall")
        dx=abs(abs(c[0]-0.25)-far); dy=abs(abs(c[1])-far)
        if dx <= dy and c[0] < 0.25: return ("inlet","velocity-inlet")
        if dx <= dy: return ("outlet","pressure-outlet")
        return ("far-symmetry","symmetry")
    return write_fluent_ascii(path,dimension=2,points=points,cells=cells,boundary_name=boundary)


def cylinder_ogrid_3d(
    path: Path, *, radius: float, half_length: float, half_height: float,
    span: float, nr: int, nt: int, nz: int,
) -> dict[str,int]:
    """Extruded hexahedral O-grid for low-cost 3-D LES/DES smoke tests."""
    cross=[]
    for i in range(nr+1):
        blend=(i/nr)**1.7
        for j in range(nt):
            th=2*math.pi*j/nt; ct,st=math.cos(th),math.sin(th)
            ro=min(half_length/max(abs(ct),1e-14),half_height/max(abs(st),1e-14))
            rr=radius+blend*(ro-radius); cross.append((rr*ct,rr*st))
    nc=len(cross); points=[]
    for k in range(nz+1):
        z=span*k/nz
        points.extend((x,y,z) for x,y in cross)
    nid=lambda k,i,j:k*nc+i*nt+(j%nt)
    cells=[(nid(k,i,j),nid(k,i+1,j),nid(k,i+1,j+1),nid(k,i,j+1),nid(k+1,i,j),nid(k+1,i+1,j),nid(k+1,i+1,j+1),nid(k+1,i,j+1)) for k in range(nz) for i in range(nr) for j in range(nt)]
    def boundary(_nodes:tuple[int,...],c:Point)->tuple[str,str]:
        if c[2]<1e-10 or abs(c[2]-span)<1e-10: return ("span-symmetry","symmetry")
        if math.hypot(c[0],c[1])<radius*1.01: return ("cylinder","wall")
        dx=abs(abs(c[0])-half_length); dy=abs(abs(c[1])-half_height)
        if dx<=dy and c[0]<0:return ("inlet","velocity-inlet")
        if dx<=dy:return ("outlet","pressure-outlet")
        return ("far-symmetry","symmetry")
    result=write_fluent_ascii(path,dimension=3,points=points,cells=cells,boundary_name=boundary)
    result.update({"radial":nr,"circumferential":nt,"spanwise":nz})
    return result


def rotor_stator_2d(path:Path,*,inner_radius:float,interface_radius:float,outer_radius:float,nr_rotor:int,nr_stator:int,nt:int)->dict[str,int]:
    """Two non-conformal named fluid zones with duplicate sliding-interface nodes."""
    rotor=[]
    for i in range(nr_rotor+1):
        q=i/nr_rotor
        for j in range(nt):
            th=2*math.pi*j/nt; ri=inner_radius*(1+.18*math.cos(4*th));r=ri+q*(interface_radius-ri);rotor.append((r*math.cos(th),r*math.sin(th)))
    stator=[]
    for i in range(nr_stator+1):
        q=i/nr_stator;r=interface_radius+q*(outer_radius-interface_radius)
        for j in range(nt):th=2*math.pi*j/nt;stator.append((r*math.cos(th),r*math.sin(th)))
    points=rotor+stator;split=len(rotor);rid=lambda i,j:i*nt+(j%nt);sid=lambda i,j:split+i*nt+(j%nt)
    rc=[(rid(i,j),rid(i+1,j),rid(i+1,j+1),rid(i,j+1)) for i in range(nr_rotor) for j in range(nt)]
    sc=[(sid(i,j),sid(i+1,j),sid(i+1,j+1),sid(i,j+1)) for i in range(nr_stator) for j in range(nt)]
    cells=rc+sc
    def boundary(nodes:tuple[int,...],c:Point)->tuple[str,str]:
        rr=math.hypot(c[0],c[1])
        is_rotor=min(nodes)<split
        if is_rotor and rr<inner_radius*1.3:return ("impeller-wall","wall")
        if abs(rr-interface_radius)<.02*interface_radius:return (("rotor-interface" if is_rotor else "stator-interface"),"wall")
        return ("tank-wall","wall")
    out=write_fluent_ascii(path,dimension=2,points=points,cells=cells,boundary_name=boundary,cell_zone_names=["rotor"]*len(rc)+["stator"]*len(sc))
    out.update({"rotor_cells":len(rc),"stator_cells":len(sc),"circumferential":nt})
    return out


def split_inlet_channel_2d(path:Path,*,length:float,height:float,nx:int,ny:int)->dict[str,int]:
    xs=[length*i/nx for i in range(nx+1)];ys=[-height/2+height*j/ny for j in range(ny+1)];points=[(x,y) for y in ys for x in xs];nid=lambda i,j:j*(nx+1)+i;cells=[(nid(i,j),nid(i+1,j),nid(i+1,j+1),nid(i,j+1)) for j in range(ny) for i in range(nx)]
    tol=1e-10
    def boundary(_nodes:tuple[int,...],c:Point)->tuple[str,str]:
        if abs(c[0])<tol:return (("inlet-upper" if c[1]>=0 else "inlet-lower"),"velocity-inlet")
        if abs(c[0]-length)<tol:return ("outlet","pressure-outlet")
        return ("channel-wall","wall")
    return write_fluent_ascii(path,dimension=2,points=points,cells=cells,boundary_name=boundary)
